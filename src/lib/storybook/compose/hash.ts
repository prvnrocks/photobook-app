// Content hash of a book-doc element (Task 7): 12 hex chars, stable across runs and platforms.
// Pure, no crypto import (also used client-side). Not a security hash — it only tells "unchanged
// since the composer wrote it" from "changed by the user" (meta.story.hashes).

/** JSON with object keys sorted (arrays keep their order); `undefined` values are dropped like JSON.stringify. */
export function stableJson(value: unknown): string {
  if (value === null || typeof value !== "object") return JSON.stringify(value) ?? "null";
  if (Array.isArray(value)) return `[${value.map((v) => (v === undefined ? "null" : stableJson(v))).join(",")}]`;
  const entries = Object.entries(value as Record<string, unknown>)
    .filter(([, v]) => v !== undefined)
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  return `{${entries.map(([k, v]) => `${JSON.stringify(k)}:${stableJson(v)}`).join(",")}}`;
}

/** Two 32-bit FNV-1a variants over the stable JSON → 12 hex chars. */
export function contentHash(value: unknown): string {
  const s = stableJson(value);
  let h1 = 0x811c9dc5;
  let h2 = 0x9747b28c;
  for (let i = 0; i < s.length; i++) {
    const c = s.charCodeAt(i);
    h1 = Math.imul(h1 ^ c, 0x01000193);
    h2 = Math.imul(h2 ^ c, 0x5bd1e995);
    h2 ^= h2 >>> 15;
  }
  return ((h1 >>> 0).toString(16).padStart(8, "0") + (h2 >>> 0).toString(16).padStart(8, "0")).slice(0, 12);
}
